import { readdir, readFile, writeFile } from 'node:fs/promises';

const names = (await readdir('public/media', { withFileTypes: true }))
  .filter(entry => entry.isFile()).map(entry => `/media/${entry.name}`).sort();
const content = `// Generated by scripts/generate-media.ts from public/media.\nexport const bundledMedia = new Set<string>(${JSON.stringify(names, null, 2)});\n`;
const target = 'server/mediaManifest.ts';
if (await readFile(target, 'utf8').catch(() => '') !== content) await writeFile(target, content);
